# ----------------------------------------------------------------------
# RGPO（距离门拖引）+ VGPO 联合拖引配置  —— 2026-10-18 创新性提升方案 C1
# ----------------------------------------------------------------------
# 模型：  ΔR_j(t) = f_j(mod(t,T_j)/T_j) · D_j              （距离偏置, m）
#         ΔV_j(t) = ρ_j · dΔR_j/dt + (1−ρ_j) · ΔV_j^VGPO(t) （多普勒偏置, m/s）
#   ρ=0 且 D=0  → 现稿模型（逐位不变）
#   ρ=1          → 相干拖引（假目标距离-距离率自洽）
# spread_i      → 第 i 架机的偏置缩放（None=共同模态；[1.0,0.6,1.3]=差分模态）
#
# 设计约定：D_j = V_j · T_j 使线性相干拖引的速率 dΔR/dt = V_j，
#           与现稿 VGPO 的峰值偏置同量级，便于横向对比。
# ----------------------------------------------------------------------
def _rgpo(kind, T, V, D, rho, spread=None):
    return dict(kind=list(kind), T=list(T), V=list(V), D=list(D),
                rho=list(rho), spread=spread)


# 三重线性 · 非相干（ρ=0，但补上物理上本应存在的距离偏置）
